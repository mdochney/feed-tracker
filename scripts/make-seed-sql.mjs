#!/usr/bin/env node
// Turn seeds/*.csv into a migration that inserts any source not already present.
//   node scripts/make-seed-sql.mjs migrations/0002_seed_sources.sql

import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseCsv } from '../src/csv.js';

const root = path.resolve(import.meta.dirname, '..');
const out = process.argv[2];
if (!out) { console.error('Usage: node scripts/make-seed-sql.mjs <output.sql>'); process.exit(1); }

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const lines = ['-- Generated by scripts/make-seed-sql.mjs from seeds/*.csv. Safe to re-run: existing keys are skipped.'];
let n = 0;
for (const f of (await readdir(path.join(root, 'seeds'))).filter((f) => f.endsWith('.csv')).sort()) {
  for (const r of parseCsv(await readFile(path.join(root, 'seeds', f), 'utf8'))) {
    if (!r.key || !r.feed_url) continue;
    lines.push(`INSERT OR IGNORE INTO sources (key, platform, name, feed_url, active) VALUES (${q(r.key)}, ${q(r.platform)}, ${q(r.name)}, ${q(r.feed_url)}, ${r.active === '0' ? 0 : 1});`);
    n++;
  }
}
await writeFile(path.resolve(out), lines.join('\n') + '\n');
console.log(`${n} sources written to ${out}`);
